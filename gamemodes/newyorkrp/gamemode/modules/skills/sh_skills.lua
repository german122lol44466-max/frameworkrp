-- уровень навыка (клиенту — из NW, серверу — из персонажа)
function SK.Level(ply, id)
	if SERVER then return ply.nyrpChar and ply.nyrpChar.skills and ply.nyrpChar.skills[id] or 0 end
	return ply:GetNW2Int("nyrp.skill." .. id, 0)
end
