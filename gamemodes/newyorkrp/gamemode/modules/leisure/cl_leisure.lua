--[[
	Развлечения: строки в справке (/help) — команды админа и клавиши для блэкджека, аркады и бумбокса.
	Модуль справки (ux) грузится позже, поэтому добавляем после загрузки всего режима.
]]

NYRP.Leisure = NYRP.Leisure or {}
local LS = NYRP.Leisure

function LS.AddHelp()
	local H = NYRP.Help
	if not H or not H.AddCommand or not H.AddKey then return end
	if LS.HelpAdded then return end
	LS.HelpAdded = true
	H.AddCommand("/blackjack", "", "Поставить стол для блэкджека (сохраняется для карты; также спавн-меню)", true, "Мир и карта")
	H.AddCommand("/blackjackremove", "", "Убрать стол для блэкджека, на который смотрите", true, "Мир и карта")
	H.AddCommand("/arcade", "", "Поставить аркадный автомат (сохраняется для карты; также спавн-меню)", true, "Мир и карта")
	H.AddCommand("/arcaderemove", "", "Убрать аркадный автомат, на который смотрите", true, "Мир и карта")
	H.AddKey("E", "По столу для блэкджека — сесть (ставка $5–$500, «Ещё / Хватит / Удвоить», блэкджек 3:2)", "Развлечения")
	H.AddKey("E", "По аркадному автомату — «Змейка» или «Реакция» за $1, таблица рекордов", "Развлечения")
	H.AddKey("↑ ↓ ← →  /  WASD", "Аркада, «Змейка»: управление", "Развлечения")
	H.AddKey("ЛКМ / ПРОБЕЛ", "Аркада, «Реакция»: нажать, когда экран стал зелёным", "Развлечения")
	H.AddKey("ПКМ", "Предмет «Бумбокс» в сумке — «Поставить»", "Развлечения")
	H.AddKey("E", "По бумбоксу: владельцу — станция, громкость, выключить, забрать; остальным — своя громкость и выключатель чужих бумбоксов", "Развлечения")
end

hook.Add("InitPostEntity", "nyrp.leisure.help", function() LS.AddHelp() end)
LS.AddHelp()   -- при перезагрузке файла (справка уже есть)
